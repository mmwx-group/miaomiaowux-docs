import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

// 落地页命令面板搜索索引:从 Starlight 的文档内容(src/content/docs)生成。
// 中文页在 src/content/docs/<slug>.md(x),英文页在 src/content/docs/en/<slug>.md(x);
// 两者合并进同一条目(href 指向中文页,英文正文只参与匹配)。

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const contentDir = path.join(rootDir, "src/content/docs");

function parseFrontmatter(src) {
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { data: {}, body: src };
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim();
    if (
      (v.startsWith('"') && v.endsWith('"')) ||
      (v.startsWith("'") && v.endsWith("'"))
    ) {
      v = v.slice(1, -1);
    }
    data[kv[1]] = v;
  }
  return { data, body: src.slice(m[0].length) };
}

// 把 markdown / mdx 正文压成纯文本:去 import、JSX 标签、图片、链接语法、提示框标记、表格分隔线。
function toPlainText(body) {
  return body
    .replace(/^import\s.+$/gm, " ")
    .replace(/<DocDemo[^>]*\/>/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/<\/?[A-Za-z][^>]*>/g, " ")
    .replace(/^:::[a-z]*(\[[^\]]*\])?\s*$/gm, " ")
    .replace(/^\s*\|?\s*-{3,}[\s|:-]*$/gm, " ")
    .replace(/[`#*_>|]/g, " ")
    .replace(/\\([.\[\]()*_])/g, "$1");
}

function normalize(text) {
  return text.replace(/\s+/g, " ").trim();
}

function buildNgrams(text) {
  const tokens = [];
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    if (/[一-鿿]/.test(ch)) {
      if (i + 1 < text.length && /[一-鿿]/.test(text[i + 1])) {
        tokens.push(text.slice(i, i + 2));
      } else {
        tokens.push(ch);
      }
      i++;
    } else if (/[A-Za-z0-9_]/.test(ch)) {
      let j = i;
      while (j < text.length && /[A-Za-z0-9_]/.test(text[j])) j++;
      tokens.push(text.slice(i, j));
      i = j;
    } else {
      i++;
    }
  }
  return tokens.join(" ");
}

function readDoc(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return null;
  const { data, body } = parseFrontmatter(fs.readFileSync(filePath, "utf-8"));
  return {
    title: data.title || "",
    description: data.description || "",
    text: normalize(toPlainText(body)),
  };
}

function findDoc(dir, slug) {
  for (const ext of [".md", ".mdx"]) {
    const p = path.join(dir, slug + ext);
    if (fs.existsSync(p)) return p;
  }
  return null;
}

const entries = [];
const files = fs
  .readdirSync(contentDir)
  .filter((f) => /\.mdx?$/.test(f))
  .sort();

for (const file of files) {
  const slug = file.replace(/\.mdx?$/, "");
  const zh = readDoc(path.join(contentDir, file));
  const en = readDoc(findDoc(path.join(contentDir, "en"), slug));
  if (!zh) continue;

  const href = slug === "index" ? "/docs" : `/docs/${slug}`;
  const zhContent = normalize([zh.title, zh.description, zh.text].join(" "));
  const enContent = en
    ? normalize([en.title, en.description, en.text].join(" "))
    : "";

  entries.push({
    href,
    pageTitle: zh.title || slug,
    description: zh.description,
    section: "docs",
    content: normalize(zhContent + " " + enContent),
    ngramContent: buildNgrams(zhContent),
    sections: [],
  });
}

const outputPath = path.join(rootDir, "src/generated/search-index.ts");
const tsContent = `// Auto-generated by scripts/generate-search-index.mjs
// Do not edit manually

export type SearchEntry = {
  href: string
  pageTitle: string
  description: string
  section: 'docs' | 'x-docs'
  content: string
  ngramContent: string
  sections: Array<{ heading: string; text: string }>
}

export const searchIndex: SearchEntry[] = ${JSON.stringify(entries, null, 2)}
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, tsContent, "utf-8");

console.log(`Generated search index: ${entries.length} pages indexed`);
for (const entry of entries) {
  console.log(
    `  ${entry.section.padEnd(6)} ${entry.href.padEnd(40)} ${entry.pageTitle.padEnd(24)} content=${entry.content.length} ngram=${entry.ngramContent.length}`,
  );
}
